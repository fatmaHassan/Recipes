    public static function forName(string $name): string
    {
        $key = mb_strtolower(trim($name));

        if ($key === '') {
            return self::OTHER;
        }

        if (isset(self::MAP[$key])) {
            return self::MAP[$key];
        }

        foreach (self::RULES as $pattern => $category) {
            if (preg_match($pattern, $key) === 1) {
                return $category;
            }
        }

        return self::OTHER;
    }

    /**
     * All categories in display order.
     *
     * @return string[]
     */
    public static function all(): array
    {
        return self::CATEGORIES;
    }

    /**
     * Filter the curated popular staples down to the given TheMealDB catalog,
     * preserving curated order and silently skipping staples that are missing
     * from the catalog (matching is case-insensitive). Catalog items are
     * arrays with at least a 'name' key.
     *
     * @param  array<int, array<string, mixed>>  $catalog
     * @return array<int, array<string, mixed>>
     */
    public static function popularFromCatalog(array $catalog): array
    {
        $byLowerName = [];

        foreach ($catalog as $item) {
            $byLowerName[mb_strtolower((string) ($item['name'] ?? ''))] = $item;
        }

        $popular = [];

        foreach (self::POPULAR_STAPLES as $name) {
            $item = $byLowerName[mb_strtolower($name)] ?? null;

            if ($item !== null) {
                $popular[] = $item;
            }
        }

        return $popular;
    }
